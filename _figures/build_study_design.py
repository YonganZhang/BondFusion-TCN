"""Generate editable Fig. 1 in TikZ and native draw.io from the same node/edge specification.
Coordinates are millimetres; diagram is schematic, with no synthetic experimental traces.
"""
from pathlib import Path
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
GRAY = 'EBEBEB'
PURPLE = 'E3DCEE'
WHITE = 'FFFFFF'
# id, centre x/y, width/height, text lines, fill
NODES = [
    ('curves', 23, 12, 36, 10, ['Conventional curves', 'GR, CBL, CCL'], GRAY),
    ('vdl', 23, 26, 36, 10, ['VDL waveform'], PURPLE),
    ('env', 81, 26, 42, 10, ['Log-envelope', 'block features'], PURPLE),
    ('fusion', 144, 26, 48, 10, ['Concatenate at each depth', 'curves + VDL features'], PURPLE),
    ('refin', 26, 55, 42, 10, ['Curves only'], GRAY),
    ('refmodel', 91, 55, 48, 12, ['Depth-sequence model', 'reference branch'], GRAY),
    ('refout', 153, 55, 43, 12, ['Bond class at each depth', 'Poor / Moderate / Good'], WHITE),
    ('jointin', 26, 75, 42, 10, ['Curves + VDL features'], PURPLE),
    ('jointmodel', 91, 75, 48, 12, ['Same architecture family', 'fusion branch'], PURPLE),
    ('jointout', 153, 75, 43, 12, ['Bond class at each depth', 'Poor / Moderate / Good'], WHITE),
    ('train', 25, 112, 40, 14, ['Training wells A--D', 'screening and tuning'], WHITE),
    ('freeze', 70, 112, 31, 14, ['Freeze choices', 'final training'], WHITE),
    ('test', 115, 112, 40, 14, ['Held-out wells E, F', 'evaluate frozen models'], WHITE),
    ('assess', 160, 112, 34, 14, ['Paired input', 'comparison'], WHITE),
]
# source, target, optional intermediate waypoints (input/output ports implicit)
EDGES = [('vdl', 'env', []), ('env', 'fusion', []),
         ('curves', 'fusion', [(144, 12)]),
         ('refin', 'refmodel', []), ('refmodel', 'refout', []),
         ('jointin', 'jointmodel', []), ('jointmodel', 'jointout', []),
         ('train', 'freeze', []), ('freeze', 'test', []), ('test', 'assess', [])]
TEXT = [(2, 1, 'a', True), (10, 1, 'Depth-aligned inputs and waveform representation', False),
        (65, 5, 'Alignment and fusion', False),
        (2, 40, 'b', True), (10, 40, 'Paired sequence-based classification', False),
        (5, 87, 'LSTM, GRU, Transformer, Reformer, Crossformer, TimesNet, TimeMixer, ModernTCN', False),
        (5, 93, 'Independent parameters and tuning; matched search budgets for the two inputs', False),
        (2, 101, 'c', True), (10, 101, 'Evaluation and supporting design comparison', False),
        (5, 127, 'Supporting analysis: fixed block features versus learned waveform encoders on ModernTCN', False)]

def tex_escape(t):
    return t.replace('&', r'\&').replace('_', r'\_')

def build_tikz():
    s = [r'% Generated by build_study_design.py; editable vector diagram.',
         r'\documentclass[tikz,border=2pt]{standalone}', r'\usepackage{mathptmx}',
         r'\usetikzlibrary{arrows.meta}',
         r'\definecolor{curvefill}{HTML}{EBEBEB}', r'\definecolor{vdlfill}{HTML}{E3DCEE}',
         r'\begin{document}', r'\begin{tikzpicture}[x=1mm,y=-1mm,font=\fontsize{9}{10.5}\selectfont,',
         r'  >={Stealth[length=1.8mm]}, every node/.style={inner sep=1.6pt},',
         r'  flow/.style={->,draw=black!75,line width=0.6pt}]',
         r'\path[use as bounding box] (0,0) rectangle (180,133);']
    for yy in [35,98]: s.append(fr'\draw[black!20,line width=0.4pt] (0,{yy}) -- (180,{yy});')
    for ident,x,y,w,h,lines,fill in NODES:
        color = {GRAY:'curvefill',PURPLE:'vdlfill',WHITE:'white'}[fill]
        label = r'\\'.join(tex_escape(t) for t in lines)
        s.append(fr'\node[draw=black!65,rounded corners=1.5pt,fill={color},align=center,text width={w-2}mm,minimum height={h}mm] ({ident}) at ({x},{y}) {{{label}}};')
    for source,target,points in EDGES:
        if points:
            route=' -- '.join(f'({x},{y})' for x,y in points)
            s.append(fr'\draw[flow] ({source}.east) -- {route} -- ({target}.north);')
        else: s.append(fr'\draw[flow] ({source}.east) -- ({target}.west);')
    for x,y,label,bold in TEXT:
        font = r'\bfseries' if bold else ''
        s.append(fr'\node[anchor=north west,font=\fontsize{{9}}{{10.5}}\selectfont{font}] at ({x},{y}) {{{tex_escape(label)}}};')
    s += [r'\end{tikzpicture}',r'\end{document}']
    (HERE/'fig_01_study_design.tex').write_text('\n'.join(s)+'\n')

def build_drawio():
    scale=5
    mx = ET.Element('mxfile', host='app.diagrams.net')
    d = ET.SubElement(mx,'diagram',id='study-design',name='Fig 1')
    g = ET.SubElement(d,'mxGraphModel',dx='900',dy='665',page='1',pageWidth='900',pageHeight='665')
    root=ET.SubElement(g,'root');ET.SubElement(root,'mxCell',id='0');ET.SubElement(root,'mxCell',id='1',parent='0')
    for ident,x,y,w,h,lines,fill in NODES:
        c=ET.SubElement(root,'mxCell',id=ident,value='<br>'.join(t.replace('--','–') for t in lines),vertex='1',parent='1',
          style=f'rounded=1;whiteSpace=wrap;html=1;fillColor=#{fill};strokeColor=#595959;fontFamily=Times New Roman;fontSize=16;')
        ET.SubElement(c,'mxGeometry',x=str((x-w/2)*scale),y=str((y-h/2)*scale),width=str(w*scale),height=str(h*scale),attrib={'as':'geometry'})
    for i,(source,target,points) in enumerate(EDGES):
        style='endArrow=block;html=1;rounded=0;strokeColor=#404040;exitX=1;exitY=0.5;entryX=0;entryY=0.5;'
        if points: style='endArrow=block;html=1;rounded=0;strokeColor=#404040;exitX=1;exitY=0.5;entryX=0.5;entryY=0;'
        c=ET.SubElement(root,'mxCell',id=f'edge{i}',edge='1',parent='1',source=source,target=target,style=style)
        geom=ET.SubElement(c,'mxGeometry',relative='1',attrib={'as':'geometry'})
        if points:
            arr=ET.SubElement(geom,'Array',attrib={'as':'points'})
            for x,y in points: ET.SubElement(arr,'mxPoint',x=str(x*scale),y=str(y*scale))
    for i,(x,y,label,bold) in enumerate(TEXT):
        c=ET.SubElement(root,'mxCell',id=f'text{i}',value=label,vertex='1',parent='1',
           style=f'text;html=1;whiteSpace=wrap;align=left;verticalAlign=top;fontFamily=Times New Roman;fontSize=16;fontStyle={1 if bold else 0};')
        ET.SubElement(c,'mxGeometry',x=str(x*scale),y=str(y*scale),width=str(30 if bold else (180-x)*scale),height='28',attrib={'as':'geometry'})
    ET.indent(mx)
    ET.ElementTree(mx).write(HERE/'fig_01_study_design.drawio',encoding='utf-8',xml_declaration=True)

if __name__ == '__main__':
    build_tikz();build_drawio()
    print('Fig. 1 TikZ and draw.io generated from one specification')
